#!/usr/bin/env node
// Rerunnable: extracts the raw SVG path geometry (id, name, d) from the
// `body-muscles` npm package (Apache-2.0, https://github.com/vulovix/body-muscles)
// into ATLAS's vendored data file. Nothing ATLAS-specific is added -- the
// mapping onto ATLAS's muscle taxonomy lives in
// apps/web/src/anatomy/anatomyMapping.ts, where it can be reviewed and tested.
//
// Usage:
//   npm pack body-muscles@1.0.0 && tar -xzf body-muscles-1.0.0.tgz
//   node scripts/extract-body-muscles.mjs package apps/web/src/anatomy/vendoredMuscleShapes.ts
//
// First arg: the extracted package directory (contains package.json + dist/).
// Second arg: output path. After upgrading the upstream version, re-run
// `npm test` -- anatomyMapping.test.ts pins the upstream shape counts and
// fails until the mapping/allowlist has been re-reviewed against the new data.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [packageDir, outputPath] = process.argv.slice(2);
if (!packageDir || !outputPath) {
  console.error('Usage: node scripts/extract-body-muscles.mjs <extracted package dir> <output path>');
  process.exit(1);
}

const require = createRequire(import.meta.url);
const root = resolve(packageDir);
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf-8'));
const { FRONT_MUSCLES } = require(resolve(root, 'dist/data/muscles.front.js'));
const { BACK_MUSCLES } = require(resolve(root, 'dist/data/muscles.back.js'));

const escape = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

function render(name, shapes) {
  const ids = new Set();
  let out = `export const ${name}: VendoredMuscleShape[] = [\n`;
  for (const { id, name: label, path } of shapes) {
    if (ids.has(id)) throw new Error(`Duplicate upstream shape id in ${name}: ${id}`);
    ids.add(id);
    out += `  { id: '${escape(id)}', name: '${escape(label)}', d: '${escape(path)}' },\n`;
  }
  return out + '];\n';
}

const header = `/**
 * GENERATED by scripts/extract-body-muscles.mjs -- do not edit by hand.
 *
 * Vendored anatomical SVG path geometry from the \`${pkg.name}\` npm package,
 * v${pkg.version} (${pkg.license}, ${pkg.repository?.url ?? ''}). Only each
 * shape's \`id\`, \`name\` and path \`d\` were extracted, unmodified and in
 * upstream order; none of the package's rendering, color or state logic is
 * used. Front shapes use viewBox "0 0 35 93", back shapes "37 0 35 93".
 *
 * Nothing ATLAS-specific is stored here. How these shapes map onto ATLAS's
 * canonical muscle taxonomy -- including every intentional shared/fallback
 * mapping -- lives in anatomyMapping.ts. License text and the upstream NOTICE
 * ship in apps/web/public/licenses/body-muscles/; see NOTICE.md in this
 * directory and LICENSES/README.md for provenance.
 */
export interface VendoredMuscleShape {
  id: string;
  name: string;
  d: string;
}

`;

writeFileSync(outputPath, header + render('FRONT_MUSCLE_SHAPES', FRONT_MUSCLES) + '\n' + render('BACK_MUSCLE_SHAPES', BACK_MUSCLES));
console.log(`Wrote ${FRONT_MUSCLES.length} front + ${BACK_MUSCLES.length} back shapes from ${pkg.name}@${pkg.version} to ${outputPath}`);
